export function buildCombinedInsight(cards) {
  if (cards.length < 3) return "";
  return `${cards[0].reflection} ${cards[1].meaning} ${cards[2].question}`;
}
export function cardArtStyle(card) {
  return {
    background: card.palette,
    "--card-accent": card.accent,
  };
}
export function cardPosition(index, total) {
  const progress = total <= 1 ? 0 : index / (total - 1);
  const normalized = progress * 2 - 1;
  const angle = normalized * 34;
  const curve = Math.pow(Math.abs(normalized), 1.65);
  return {
    "--x-desktop": `${normalized * 465}px`,
    "--x-mobile": `${normalized * 345}px`,
    "--y-desktop": `${curve * 92}px`,
    "--y-mobile": `${curve * 58}px`,
    "--r": `${angle}deg`,
    "--d": `${Math.min(index * 0.025, 0.4)}s`,
  };
}
